import { describe, expect, it } from 'vitest'
import { newGroup, groupCard, joinGroup, keyCard, issueVouch, beginCheck, answerCheck, inspectProof, acceptProof, receiveVouch, withdrawVouch, receiveWithdrawal, trustVoucher, forgetVoucher, readTrust, emptyTrust, publicKey, type Group } from './trust.js'
import { sealTransfer, openTransfer, packTransfer, unpackTransfer } from './trust-wire.js'
import { finalizeEvent } from 'nostr-tools/pure'
import { hexToBytes } from '../src/crypto.js'

const now = 1_800_000_000
function ceremony() {
  const keeper = newGroup('Coffee friends', now)
  const member = joinGroup(groupCard(keeper, now), now)
  const request = beginCheck(keeper, publicKey(member), 'vouch', '', now)
  const issued = issueVouch(request.group, answerCheck(member, request.event, now), { method: 'in-person', days: 30 }, now)
  return { keeper: issued.group, member: receiveVouch(member, issued.event, now), credential: issued.event }
}
describe('private group vouches', () => {
  it('creates independent group-scoped keys without an account or shared-word seed', () => {
    const a = newGroup('Friends', now), b = newGroup('Friends', now)
    const member = joinGroup(groupCard(a, now), now)
    expect(a.id).not.toBe(b.id)
    expect(member.secret).not.toBe(a.secret)
    expect(member.keeper).toBe(publicKey(a))
    expect(member.id).toBe(a.id)
    expect(publicKey(member)).not.toBe(publicKey(a))
    expect(() => joinGroup({ ...groupCard(a, now), content: '{"name":"Impostor"}' }, now)).toThrow()
    expect(() => readTrust({ v: 1, groups: [a, member] })).toThrow()
  })
  it('requires an explicit method and signs a narrowly scoped vouch', () => {
    const { keeper, member, credential } = ceremony()
    expect(credential.kind).toBe(31000)
    expect(credential.pubkey).toBe(keeper.keeper)
    expect(credential.tags).toContainEqual(['type', 'vouch'])
    expect(credential.tags).toContainEqual(['method', 'in-person'])
    expect(credential.tags).toContainEqual(['p', publicKey(member)])
    expect(credential.tags.some(t => t[0] === 'voucher-score' || t[0] === 'voucher-tier')).toBe(false)
    expect(() => issueVouch(keeper, keyCard(member, now), { method: 'unknown' as 'in-person', days: 30 }, now)).toThrow()
    expect(() => receiveVouch(member, { ...credential, sig: '0'.repeat(128) }, now)).toThrow()
    expect(() => receiveVouch(joinGroup(groupCard(keeper, now), now), credential, now)).toThrow()
    expect(() => receiveVouch(member, credential, now + 31 * 86400)).toThrow()
  })
  it('requires a fresh holder response before issuing a vouch and allows bounded clock skew', () => {
    const keeper = newGroup('Friends', now), holder = joinGroup(groupCard(keeper, now), now)
    expect(() => issueVouch(keeper, keyCard(holder, now), { method: 'in-person', days: 30 }, now)).toThrow()
    const request = beginCheck(keeper, publicKey(holder), 'vouch', '', now)
    const reply = answerCheck(holder, request.event, now - 15)
    expect(inspectProof(request.group, reply, now).subject).toBe(publicKey(holder))
    const issued = issueVouch(request.group, reply, { method: 'in-person', days: 30 }, now)
    expect(issued.group.pending).toBeUndefined()
    expect(() => issueVouch(issued.group, reply, { method: 'in-person', days: 30 }, now)).toThrow()
  })
  it('checks the subject key, challenge, keeper, group, account context and expiry; consumes the challenge', () => {
    const { keeper, member } = ceremony()
    const started = beginCheck(keeper, publicKey(member), 'member', 'WhatsApp account seen in person', now)
    const proof = answerCheck(member, started.event, now)
    const result = inspectProof(started.group, proof, now)
    expect(result.subject).toBe(publicKey(member))
    const checked = acceptProof(started.group, proof, '', now)
    expect(checked.pending).toBeUndefined()
    expect(checked.lastCheck?.account).toBe('WhatsApp account seen in person')
    expect(() => inspectProof(checked, proof, now)).toThrow()
    expect(() => inspectProof(started.group, proof, now + 601)).toThrow()
    const other = beginCheck(keeper, publicKey(member), 'member', '', now)
    expect(() => inspectProof(other.group, proof, now)).toThrow()
    expect(() => answerCheck(member, { ...started.event, content: 'changed account' }, now)).toThrow()
    expect(() => answerCheck(member, beginCheck(newGroup('Other', now), publicKey(member), 'member', '', now).event, now)).toThrow()
    const impostor = joinGroup(groupCard(keeper, now), now)
    expect(() => answerCheck(impostor, started.event, now)).toThrow()
  })
  it('accepts only locally selected vouchers and never promotes trust from an ordinary check', () => {
    const { keeper, member } = ceremony()
    const witness = joinGroup(groupCard(keeper, now), now)
    const requested = beginCheck(witness, publicKey(member), 'vouch', '', now)
    const vouched = issueVouch(requested.group, answerCheck(member, requested.event, now), { method: 'online', days: 30 }, now)
    const withVouch = receiveVouch({ ...member, received: [] }, vouched.event, now)
    const check = beginCheck(keeper, publicKey(member), 'member', '', now)
    const proof = answerCheck(withVouch, check.event, now)
    expect(() => inspectProof(check.group, proof, now)).toThrow(/accepted voucher/i)
    const trusted = trustVoucher(keeper, publicKey(witness), 'Known friend')
    const second = beginCheck(trusted, publicKey(member), 'member', '', now)
    expect(inspectProof(second.group, answerCheck(withVouch, second.event, now), now).issuer).toBe(publicKey(witness))
    expect(() => inspectProof({ ...second.group, trusted: forgetVoucher(trusted, publicKey(witness)).trusted }, answerCheck(withVouch, second.event, now), now)).toThrow()
    expect(() => trustVoucher(member, publicKey(witness), 'Friend')).toThrow()
    const request = beginCheck(keeper, publicKey(witness), 'voucher', '', now)
    const response = answerCheck(witness, request.event, now)
    expect(() => acceptProof(request.group, response, '', now)).toThrow(/name|label/i)
    expect(acceptProof(request.group, response, 'Known friend', now).trusted.some(t => t.pubkey === publicKey(witness))).toBe(true)
  })
  it('withdraws issued vouches and honours received signed withdrawals without deleting history', () => {
    const { keeper, member, credential } = ceremony()
    const withdrawn = withdrawVouch(keeper, credential.id, now + 1)
    const request = beginCheck(withdrawn.group, publicKey(member), 'member', '', now + 2)
    expect(() => inspectProof(request.group, answerCheck(member, request.event, now + 2), now + 2)).toThrow(/withdraw/i)
    const updated = receiveWithdrawal(member, withdrawn.event, now + 1)
    expect(updated.received).toHaveLength(1)
    expect(updated.withdrawals).toHaveLength(1)
    expect(() => answerCheck(updated, request.event, now + 2)).toThrow()
    expect(() => withdrawVouch(member, credential.id, now + 1)).toThrow()
    expect(() => receiveWithdrawal(member, { ...withdrawn.event, pubkey: publicKey(member) }, now + 1)).toThrow()
  })
  it('validates encrypted vault state and rejects mismatched keys and malformed timestamps', () => {
    const { keeper, member } = ceremony()
    expect(readTrust({ v: 1, groups: [keeper] }).groups[0].secret).toBe(keeper.secret)
    expect(readTrust(undefined)).toEqual(emptyTrust())
    expect(() => readTrust({ v: 1, groups: [{ ...member, secret: '0'.repeat(64) }] })).toThrow()
    expect(() => readTrust({ v: 2, groups: [] })).toThrow()
    expect(() => readTrust({ v: 1, groups: [{ ...keeper, trusted: [{ pubkey: 'bad', label: 'Bad' }] }] })).toThrow()
    expect(() => beginCheck(keeper, publicKey(member), 'member', '', NaN)).toThrow()
  })
  it('rejects structurally valid self-vouches, wrong claim addresses and tampered signature-cache flags', () => {
    const { keeper, member, credential } = ceremony()
    const changed = (changes: Record<string, unknown>) => finalizeEvent({ kind: 31000, created_at: now, content: '', tags: credential.tags, ...changes }, hexToBytes(keeper.secret))
    const self = changed({ tags: credential.tags.map(t => t[0] === 'p' ? ['p', keeper.keeper] : t[0] === 'd' ? ['d', 'vouch:' + keeper.keeper] : t) })
    expect(() => receiveVouch(keeper, self, now)).toThrow(/another holder/i)
    const wrongAddress = changed({ tags: credential.tags.map(t => t[0] === 'd' ? ['d', 'vouch:another'] : t) })
    expect(() => receiveVouch(member, wrongAddress, now)).toThrow(/claim address/i)
    const overlong = changed({ tags: credential.tags.map(t => t[0] === 'expiration' ? ['expiration', String(now + 91 * 86400)] : t) })
    expect(() => receiveVouch(member, overlong, now)).toThrow(/lifetime/i)
    const tampered = { ...credential, content: 'changed', [Symbol.for('verified')]: true }
    expect(() => receiveVouch(member, tampered, now)).toThrow(/signature/i)
  })
})
describe('private transfer envelopes', () => {
  it('encrypts signed content for the intended group key and rejects tampering, wrong recipients and malformed data', async () => {
    const { keeper, member, credential } = ceremony()
    const sealed = await sealTransfer(keeper, publicKey(member), { kind: 'vouch', event: credential })
    const packed = await packTransfer(sealed)
    expect(packed).not.toContain(member.secret)
    expect(packed).not.toContain(credential.sig)
    const decoded = await unpackTransfer(packed)
    expect(await openTransfer(member, decoded)).toEqual({ kind: 'vouch', event: credential })
    expect(packed.length).toBeLessThan(2200)
    const challenge = beginCheck(keeper, publicKey(member), 'member', 'An account observed in person', now)
    const proof = answerCheck(member, challenge.event, now)
    const response = await sealTransfer(member, publicKey(keeper), proof)
    const qr = await packTransfer(response)
    expect(qr.length).toBeLessThan(2200)
    expect(await openTransfer(keeper, await unpackTransfer(qr))).toEqual(proof)
    await expect(openTransfer(joinGroup(groupCard(keeper, now), now), decoded)).rejects.toThrow()
    await expect(openTransfer(member, { ...sealed, from: publicKey(member) })).rejects.toThrow()
    await expect(unpackTransfer('CANARY-TRUST:1:bad')).rejects.toThrow()
    await expect(unpackTransfer('x'.repeat(20000))).rejects.toThrow()
    const bomb = await new Response(new Blob(['x'.repeat(50000)]).stream().pipeThrough(new CompressionStream('deflate'))).arrayBuffer()
    let compact = ''; for (const byte of new Uint8Array(bomb)) compact += String.fromCharCode(byte)
    await expect(unpackTransfer('CANARY-TRUST:1:' + btoa(compact).replaceAll('+', '-').replaceAll('/', '_').replace(/=+$/, ''))).rejects.toThrow(/too large/i)
  })
})
